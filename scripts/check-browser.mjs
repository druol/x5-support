import assert from "node:assert/strict";
import { createRequire } from "node:module";
import { mkdir } from "node:fs/promises";
const require = createRequire(import.meta.url);
const { chromium } = require("../frontend/node_modules/playwright");
const baseURL = process.env.APP_URL || "http://127.0.0.1:8090";
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1050 }, reducedMotion: "reduce" });
const errors = [];
context.on("page", page => page.on("pageerror", error => errors.push(error.message)));
const user = await context.newPage();
const admin = await context.newPage();
user.setDefaultTimeout(20000);
admin.setDefaultTimeout(20000);
try {
  await user.goto("/user");
  await user.getByRole("heading", { name: "Мои заявки", exact: true }).waitFor();
  await user.getByRole("button", { name: "Создать заявку", exact: true }).click();
  const title = `Браузерная проверка ${Date.now()}`;
  await user.getByLabel("Тема", { exact: true }).selectOption("access");
  await user.getByLabel("Заголовок", { exact: true }).fill(title);
  await user.getByLabel("Описание", { exact: true }).fill("Не получается открыть личный кабинет. Проверка полного сценария из PDF.");
  await user.getByRole("button", { name: "Отправить заявку" }).click();
  await user.waitForURL(/\/user\/tickets\/\d+$/);
  const id = user.url().split("/").pop();
  await user.getByRole("heading", { name: title, exact: true }).waitFor();
  await admin.goto("/admin");
  await admin.getByLabel("Тема", { exact: true }).selectOption("access");
  await admin.getByLabel("Статус", { exact: true }).selectOption("new");
  await admin.getByRole("link", { name: title, exact: true }).click();
  await admin.getByRole("button", { name: "Принять в работу", exact: true }).click();
  await user.locator("dl").getByText("В работе", { exact: true }).waitFor();
  await admin.getByLabel("Ваш комментарий", { exact: true }).fill("Уточнили причину ошибки");
  await admin.getByRole("button", { name: "Добавить комментарий", exact: true }).click();
  await user.getByText("Уточнили причину ошибки", { exact: true }).waitFor();
  await admin.getByRole("button", { name: "Завершить заявку", exact: true }).click();
  assert.equal(await admin.getByLabel("Результат работы").evaluate(input => input.validity.valueMissing), true);
  await admin.getByLabel("Результат работы").fill("Доступ восстановлен, можно проверить");
  await admin.getByRole("button", { name: "Завершить заявку", exact: true }).click();
  await user.locator("dl").getByText("Выполнено", { exact: true }).waitFor();
  // The user page has stayed open throughout all administrator actions.
  await user.waitForFunction(() => Number(document.querySelector('button[aria-label^="Уведомления:"]')?.textContent) >= 3);
  await user.getByRole("button", { name: /^Уведомления:/ }).click();
  const dialog = user.getByRole("dialog");
  const complete = dialog.getByRole("button").filter({ hasText: `Заявка №${id}` }).filter({ hasText: "Заявка выполнена:" });
  await complete.waitFor();
  assert.equal(await dialog.getByRole("button").filter({ hasText: `Заявка №${id}` }).count(), 3);
  await complete.click();
  await dialog.waitFor({ state: "hidden" });
  assert.ok(user.url().endsWith(`/user/tickets/${id}`));
  await user.getByRole("button", { name: "Вернуть в работу", exact: true }).click();
  assert.equal(await user.getByLabel("Причина возврата").evaluate(input => input.validity.valueMissing), true);
  await user.getByLabel("Причина возврата").fill("Ошибка осталась на другом устройстве");
  await user.getByRole("button", { name: "Вернуть в работу", exact: true }).click();
  await admin.getByText("Ошибка осталась на другом устройстве", { exact: true }).waitFor();
  await user.getByLabel("Ваш комментарий", { exact: true }).fill("Дополняю обращение: мобильный браузер");
  await user.getByRole("button", { name: "Добавить комментарий", exact: true }).click();
  await admin.getByText("Дополняю обращение: мобильный браузер", { exact: true }).waitFor();
  await user.reload();
  await user.getByText("Дополняю обращение: мобильный браузер", { exact: true }).waitFor();
  await user.getByRole("button", { name: /^Уведомления:/ }).click();
  const readItem = user.getByRole("dialog").getByRole("button").filter({ hasText: `Заявка №${id}` }).filter({ hasText: "Заявка выполнена:" });
  await readItem.getByLabel("Прочитано").waitFor();
  await user.keyboard.press("Escape");
  // Verify keyboard close, small-screen layout and deep-link reload.
  await mkdir("dev-scratch", { recursive: true });
  await user.screenshot({ path: "dev-scratch/ticket-desktop.png", fullPage: true });
  await user.setViewportSize({ width: 390, height: 844 });
  await user.screenshot({ path: "dev-scratch/ticket-mobile.png", fullPage: true });
  assert.equal(await user.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "mobile page overflows horizontally");
  await user.goto("/user");
  await user.getByRole("link", { name: title, exact: true }).waitFor();
  assert.equal(await user.evaluate(() => document.documentElement.scrollWidth > window.innerWidth), false, "mobile list overflows horizontally");
  assert.deepEqual(errors, [], "browser runtime errors");
  console.log(`PASS: browser scenario, ticket #${id}, both roles, filters, required fields, live updates, read notification, reopen, persistence, mobile layout`);
} finally {
  await browser.close();
}
